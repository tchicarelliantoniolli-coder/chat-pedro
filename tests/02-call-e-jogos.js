const { chromium } = require('playwright');
const SP = process.argv[2] || require('path').join(__dirname, 'out'), URL = 'http://localhost:3331';
const ok = (c, msg) => console.log((c ? 'OK   ' : 'FALHA') + ' ' + msg);
(async () => {
  const b = await chromium.launch({ args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
  const errs = [];
  const mk = async (w, h, touch) => { const c = await b.newContext({ viewport: { width: w, height: h }, permissions: ['microphone', 'camera'], hasTouch: !!touch, isMobile: !!touch }); const p = await c.newPage(); p.on('pageerror', e => errs.push(e.message)); return p; };
  const signup = async (p, email, nick) => { await p.goto(URL); await p.waitForTimeout(500); await p.click('#tabSignup'); await p.fill('#authEmail', email); await p.fill('#authNick', nick); await p.fill('#authPass', 'senha123'); await p.click('#authGo'); await p.waitForTimeout(900); };
  const P = await mk(1366, 650);
  await signup(P, 'p@t.com', 'Pedro');
  await P.fill('#createName', 'Galera do Pedro'); await P.click('#createForm button[type=submit]'); await P.waitForTimeout(1500);
  await P.click('#srvBtn'); await P.click('#invMake'); await P.waitForTimeout(400); const link = await P.inputValue('#invLink'); await P.click('#srvClose');
  const L = await mk(1366, 650); await signup(L, 'l@t.com', 'Lucas'); await L.goto(link); await L.waitForTimeout(800); await L.click('#invAccept'); await L.waitForTimeout(1500);
  await P.fill('#input', 'bora jogar?'); await P.press('#input', 'Enter'); await P.waitForTimeout(300);
  await P.screenshot({ path: SP + '/y-desk.png' });
  await L.click('.chan.voice[data-voice]'); await L.waitForTimeout(1000);
  ok((await P.textContent('.chan.voice .vj')).includes('1'), 'canal de voz mostra quem esta dentro: ' + await P.textContent('.chan.voice .vj'));
  await P.screenshot({ path: SP + '/y-busy.png' });
  await P.click('#trOpen'); await P.waitForTimeout(400);
  ok(await P.isVisible('#truco'), 'escolher truco na barra abre o jogo');
  await P.click('text=Criar mesa de 4'); await P.waitForTimeout(500);
  ok(await L.evaluate(() => document.getElementById('trOpen').classList.contains('on')), 'pontinho aceso para os outros quando tem mesa');
  await P.click('.chan.voice[data-voice]'); await P.waitForTimeout(1000);
  ok((await P.textContent('.chan.voice .vj')).includes('você está aqui'), 'canal de voz mostra que voce esta nele');
  await P.screenshot({ path: SP + '/y-incall.png' });
  const M = await mk(390, 800, true); await signup(M, 'm@t.com', 'Celular'); await M.goto(link); await M.waitForTimeout(800); await M.click('#invAccept'); await M.waitForTimeout(1500);
  await M.screenshot({ path: SP + '/y-mobile.png' });
  await M.tap('#railBtn'); await M.waitForTimeout(300); await M.screenshot({ path: SP + '/y-mobile-acts.png' });
  console.log('erros:', errs); await b.close();
})().catch(e => { console.error(e); process.exit(1); });
